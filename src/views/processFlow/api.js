// Flujo del Proceso · cliente HTTP de SOLO LECTURA (GET con la sesión del servidor; sin datos de demostración).
export async function getProcessFlow(signal) {
  const response = await fetch('/api/v1/analytics/process-flow', { credentials: 'same-origin', cache: 'no-store', headers: { Accept: 'application/json' }, signal });
  const body = await response.json().catch(() => ({}));
  if (!response.ok) {
    const error = new Error(response.status === 401 ? 'Tu sesión expiró. Inicia sesión nuevamente.' : response.status === 403 ? 'No tienes acceso a este módulo.' : body?.error?.message || 'No fue posible consultar MariaDB.');
    error.status = response.status; throw error;
  }
  return body;
}
